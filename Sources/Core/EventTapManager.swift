import Cocoa
import CoreGraphics
import ApplicationServices

/// Manages the low-level Quartz event tap that intercepts keystrokes system-wide.
public final class EventTapManager {
    public static let shared = EventTapManager()

    private var machPort: CFMachPort?
    private var runLoopSource: CFRunLoopSource?
    private var isRunning: Bool = false

    public var isTapActive: Bool {
        return isRunning && machPort != nil
    }

    private init() {}

    /// Starts the event tap. Returns true if successfully installed.
    @discardableResult
    public func start() -> Bool {
        guard !isRunning else { return true }

        // Must have Accessibility permissions
        guard PermissionsManager.shared.isAccessibilityGranted() else {
            print("[EventTapManager] Cannot start: Accessibility permission not granted.")
            return false
        }

        let eventMask = CGEventMask(1 << CGEventType.keyDown.rawValue)

        let callback: CGEventTapCallBack = { proxy, type, event, refcon in
            return EventTapManager.shared.handleEvent(proxy: proxy, type: type, event: event)
        }

        guard let tap = CGEvent.tapCreate(
            tap: .cgSessionEventTap,
            place: .headInsertEventTap,
            options: .defaultTap,
            eventsOfInterest: eventMask,
            callback: callback,
            userInfo: nil
        ) else {
            print("[EventTapManager] Failed to create CGEventTap.")
            return false
        }

        self.machPort = tap
        guard let source = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, tap, 0) else {
            print("[EventTapManager] Failed to create RunLoopSource.")
            return false
        }

        self.runLoopSource = source
        CFRunLoopAddSource(CFRunLoopGetMain(), source, .commonModes)
        CGEvent.tapEnable(tap: tap, enable: true)
        self.isRunning = true

        print("[EventTapManager] Event tap successfully installed and active.")
        return true
    }

    /// Stops the event tap.
    public func stop() {
        guard isRunning else { return }

        if let tap = machPort {
            CGEvent.tapEnable(tap: tap, enable: false)
        }
        if let source = runLoopSource {
            CFRunLoopRemoveSource(CFRunLoopGetMain(), source, .commonModes)
        }

        machPort = nil
        runLoopSource = nil
        isRunning = false
        WordBufferEngine.shared.reset()
        print("[EventTapManager] Event tap stopped.")
    }

    // MARK: - Event Handling

    private func handleEvent(proxy: CGEventTapProxy, type: CGEventType, event: CGEvent) -> Unmanaged<CGEvent>? {
        // Automatically re-enable if macOS temporarily suspended the tap due to timeout
        if type == .tapDisabledByTimeout || type == .tapDisabledByUserInput {
            if let tap = machPort {
                CGEvent.tapEnable(tap: tap, enable: true)
                print("[EventTapManager] Re-enabled tap after timeout.")
            }
            return Unmanaged.passRetained(event)
        }

        guard type == .keyDown else {
            return Unmanaged.passRetained(event)
        }

        // 1. Ignore synthetic events generated by our own ActionDispatcher
        let userTag = event.getIntegerValueField(.eventSourceUserData)
        if userTag == ActionDispatcher.syntheticEventTag {
            return Unmanaged.passRetained(event)
        }

        // 2. If blocker is disabled by user, pass through directly
        guard WordStore.shared.isEnabled else {
            return Unmanaged.passRetained(event)
        }

        let keyCode = event.getIntegerValueField(.keyboardEventKeycode)
        let flags = event.flags

        // 3. Cinema Mode Interception (Escape 0x35 or 'F' key 0x03)
        let isEscape = (keyCode == 0x35)
        let isFKey = (keyCode == 0x03)
        let isCmdCtrlF = flags.contains(.maskCommand) && flags.contains(.maskControl)
        let isPlainF = !flags.contains(.maskCommand) && !flags.contains(.maskControl) && !flags.contains(.maskAlternate)

        if isEscape || (isFKey && (isCmdCtrlF || isPlainF)) {
            if WordStore.shared.isCinemaModeEnabled && CinemaModeManager.shared.isFrontAppFullScreen() {
                // For plain 'f', ensure the user is not actively typing in an editable text field
                if isEscape || isCmdCtrlF || !CinemaModeManager.shared.isFocusedElementEditable() {
                    if CinemaModeManager.shared.handleExitAttempt() {
                        WordBufferEngine.shared.reset()
                        return nil // Suppress Escape / F key so media stays in full screen, and show the cinema pop up!
                    }
                }
            }
        }

        // 4. Modifier keys: Reset buffer on Command (Cmd+C/V/A) or Control shortcuts
        if flags.contains(.maskCommand) || flags.contains(.maskControl) {
            WordBufferEngine.shared.reset()
            return Unmanaged.passRetained(event)
        }

        // 5. Handle Backspace (0x33 / 51)
        if keyCode == 0x33 {
            WordBufferEngine.shared.handleBackspace()
            return Unmanaged.passRetained(event)
        }

        // 6. Navigation or cancellation keys: Reset buffer
        // 0x24: Return, 0x4C: Keypad Enter, 0x7B..0x7E: Arrow keys
        if keyCode == 0x24 || keyCode == 0x4C || (keyCode >= 0x7B && keyCode <= 0x7E) {
            WordBufferEngine.shared.reset()
            return Unmanaged.passRetained(event)
        }

        // 6. Extract Unicode characters typed
        var length = 0
        var chars = [UniChar](repeating: 0, count: 8)
        event.keyboardGetUnicodeString(maxStringLength: 8, actualStringLength: &length, unicodeString: &chars)

        guard length > 0 else {
            return Unmanaged.passRetained(event)
        }

        let typedText = String(utf16CodeUnits: chars, count: length)

        // 7. Feed into buffer and test for match
        if let match = WordBufferEngine.shared.processInput(typedText) {
            print("[EventTapManager] Blocked word matched: '\(match.matchedWord)'. Auto-deleting \(match.deleteCount) characters.")
            ActionDispatcher.shared.executeAutoDelete(characterCount: match.deleteCount)

            // Trigger Pop-Up Note if enabled and note exists
            if WordStore.shared.showPopupNotes, let note = match.note, !note.isEmpty {
                DispatchQueue.main.async {
                    PopupNoteController.shared.showNote(word: match.matchedWord, message: note)
                }
            }
        }

        // Allow the event through; auto-delete will erase it via simulated backspaces immediately after
        return Unmanaged.passRetained(event)
    }
}
